def _single_reflection(i, alpha=.4):
    fs = 16000
    source = np.array([2., 2., 1.])
    receiver = np.array([3.+i*.3, 2., 1.2])
    direct = np.linalg.norm(source-receiver)
    image = source.copy(); image[2] *= -1
    reflected = np.linalg.norm(image-receiver)
    samples = np.zeros(4000)
    onset = round(direct/343*fs)
    samples[onset] = 1/direct
    samples[round(reflected/343*fs)] = np.sqrt(1-alpha)/reflected
    return RIR(fs, samples, tuple(source), tuple(receiver),
               {"synthetic": True, "direct_sample": onset})


def test_labelled_geometry_recovers_dimensions_and_missing_wall_abstains():
    dims = np.array([5., 6., 3.])
    data = []
    for i, receiver in enumerate(([2., 3., 1.1], [2.8, 1.2, 1.7], [3.2, 4.2, 2.])):
        source = np.array([1., 1.3, 1.4]); receiver = np.array(receiver)
        labels = {}
        for axis, name in enumerate(("x_max", "y_max", "z_max")):
            image = source.copy(); image[axis] = 2*dims[axis]-source[axis]
            labels[name] = (np.linalg.norm(image-receiver)-np.linalg.norm(source-receiver))/343
        data.append(Observation(str(i), tuple(source), tuple(receiver), 48000, {},
                                np.array(list(labels.values())), {"wall_echoes_s": labels}))
    result = estimate_geometry(data)
    np.testing.assert_allclose(result["shoebox_dims_m"], dims, atol=.01)
    for obs in data:
        del obs.metadata["wall_echoes_s"]["z_max"]
    with pytest.raises(ValueError, match="all fitted planes"):
        estimate_geometry(data)


def test_position_split_rejects_repeat_orientation_leakage():
    cfg = FitConfig(bands=(1000,), bootstrap=0)
    obs = observe(_single_reflection(0), id="a", config=cfg)
    with pytest.raises(ValueError, match="position leakage"):
        check_split([obs, replace(obs, id="other-orientation", split="test")])
    with pytest.raises(ValueError, match="training positions only"):
        fit_room([replace(obs, split="test")], RoomModel(shoebox_dims_m=(8, 8, 4)), config=cfg)


def test_unlabelled_grid_pose_uses_echoes_not_room_centre():
    dims = np.array([7., 6.4, 2.7])
    shift = np.array([3., 2., 1.2])
    source = np.array([2., 1.5, 0.])
    data = []
    for i, receiver in enumerate(([-.5, -.5, -.2], [-.5, .5, .2], [-.1, 0., 0.], [-.3, .25, .1])):
        receiver = np.array(receiver)
        s, r = source+shift, receiver+shift
        echoes = []
        for axis in range(3):
            for wall in (0, dims[axis]):
                image = s.copy(); image[axis] = 2*wall-s[axis]
                echoes.append((np.linalg.norm(image-r)-np.linalg.norm(s-r))/343)
        data.append(Observation(str(i), tuple(source), tuple(receiver), 48000, {}, np.sort(echoes)))
    got = estimate_geometry(data, dims_m=dims)
    np.testing.assert_allclose(got["coordinate_translation_m"], shift, atol=.01)
    assert not got["labelled"]


def test_analytic_reflection_fit_and_bootstrap_are_deterministic():
    cfg = FitConfig(bands=(1000,), late=False, bootstrap=2, max_nfev=20,
                    fit_surfaces=("z_min",))
    observations = [observe(_single_reflection(i), id=str(i), config=cfg) for i in range(3)]
    # The analytic impulse has flat .4 absorption. With actual spectral
    # interpolation, fixed neighboring bands must describe that same reference;
    # otherwise the single free centre coefficient compensates their wrong prior.
    alpha = uniform_bands(1.); alpha["z_min"] = (.4, .4, .4, 1., .4, .4, .4)
    model = RoomModel(shoebox_dims_m=(8, 8, 4), absorption=alpha, reference_sound_speed_m_s=343.)
    a = fit_room(observations, model, config=cfg)
    b = fit_room(observations, model, config=cfg)
    assert a.model.to_json() == b.model.to_json()
    # Independent pressure-reflection coefficient, not generated by room.synth.
    assert abs(a.model.absorption["z_min"][3]-.4) < .08
    assert a.model.uncertainty["bands"]["1000"]["successful"] == 2
    assert a.model.absorption["z_min"][0] == .4  # unfitted band retains prior
    json.dumps(a.report, allow_nan=False)


def test_ref_linear_inverse_support_and_delay():
    fs = 48000
    device = np.array([1., -.65])
    ref = np.zeros(2048); ref[42:44] = device/.3
    reference = RIR(fs, ref, (1, 1, 1), (1.3, 1, 1), {"direct_sample": 42})
    room = np.zeros(6000); room[400] = 1; room[-200] = .5
    measured = RIR(fs, signal.convolve(room, device), (1, 1, 1), (2, 1, 1), {"direct_sample": 400})
    truth = RIR(fs, room, (1, 1, 1), (2, 1, 1), {"direct_sample": 400, "synthetic": True})
    got = correct_reference(measured, reference)
    target = correct_reference(truth, reference)
    n = min(len(got.samples), len(target.samples))
    assert np.linalg.norm(got.samples[:n]-target.samples[:n])/np.linalg.norm(target.samples[:n]) < .01
    assert got.metadata["reference"]["sample_origin_s"] < 0
    assert 125 not in got.metadata["reference"]["complete_bands_hz"]
    assert got.metadata["direct_sample"] > 400
    # Full linear output must retain the final reflected pulse and its FIR tail.
    assert len(got.samples) == len(measured.samples)+got.metadata["reference"]["nfft"]-1


def test_robust_bootstrap_equals_explicit_position_resampling():
    cfg = FitConfig(bands=(1000,), late=False, bootstrap=1, seed=0,
                    max_nfev=40, fit_surfaces=("z_min",))
    obs = [observe(_single_reflection(i, a), id=str(i), config=cfg)
           for i, a in enumerate((.1, .4, .85))]
    alpha = uniform_bands(1.); alpha["z_min"] = (.2,)*7
    model = RoomModel(shoebox_dims_m=(8, 8, 4), absorption=alpha, reference_sound_speed_m_s=343.)
    result = fit_room(obs, model, config=cfg)
    indices = np.random.default_rng(0).integers(3, size=3)
    replicated = [replace(obs[j], id=f"repeat-{i}") for i, j in enumerate(indices)]
    reference = fit_room(replicated, model, config=cfg.model_copy(update={"bootstrap": 0}))
    actual = result.report["uncertainty"]["bands"]["1000"]["replicates"][0][4]
    assert abs(actual-reference.model.absorption["z_min"][3]) < .002


