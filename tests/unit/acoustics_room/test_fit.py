def test_excitation_support_excludes_partial_octaves():
    rir = _single_reflection(0)
    rir.metadata["excitation"] = dict(type="ess", f_start_hz=200, f_end_hz=1100)
    obs = observe(rir, id="narrow-sweep", config=FitConfig(bands=(500, 1000), bootstrap=0))
    assert obs.bands[500].energy > 0
    assert obs.bands[1000].energy == 0
    assert all(value is None for value in obs.bands[1000].values.values())
    assert "excitation" in obs.bands[1000].reasons["edt"]


def test_material_priors_keep_provenance_and_unmeasured_band(tmp_path):
    """A synthetic catalogue installed as a plug-in (the real one is not distributed: THIRD_PARTY.md)."""
    import yaml
    (tmp_path/"materials.yaml").write_text(yaml.safe_dump({"materials": {
        "carpet_with_underlay": {"absorption_profile_refs": ["carpet_test"]}}}))
    (tmp_path/"assemblies_measured.yaml").write_text(yaml.safe_dump({"absorption_profiles": {"carpet_test": {
        "frequency_hz": {"nominal": [125, 250, 500, 1000, 2000, 4000]},
        "alpha": {"nominal": [.05, .1, .3, .5, .6, .65], "source": "synthetic", "validity": "test"}}}}))
    fit_module.use_catalogue(tmp_path)
    try:
        alpha, meta = material_prior("carpet over concrete")              # a carpet mounting, not two walls
        assert alpha[3] == .5
        assert meta["profile"] == "carpet_test" and meta["source"] == "synthetic"
        assert meta["extrapolated_bands_hz"] == [8000]
        unknown, evidence = material_prior("unspecified furniture finish")
        assert unknown == (.2,)*7
        assert evidence["profile"] is None
    finally:
        fit_module.use_catalogue(None)


def _write_canonical_kit(tmp_path, *, real_and_noise_takes=False):
    from sensorsim.acoustics.room.ingest import SweepKit
    from sensorsim.acoustics.room.rir import generate_kit_playback
    kit = dict(fs_hz=16000, f1_hz=200, f2_hz=6500, sweep_s=.12,
               fade_in_s=.005, fade_out_s=.005, peak_dbfs=-12,
               lead_silence_s=.05, tail_silence_s=.3, end_silence_s=.05,
               repeats=2, period_s=.42, first_sweep_start_s=.05,
               formula="x(t)=sin(2*pi*f1*L*(exp(t/L)-1)), L=T/ln(f2/f1); half-Hann fades",
               reference="numerical CLI test", dither="none")
    (tmp_path/"sweep_kit.json").write_text(json.dumps(kit))
    playback = generate_kit_playback(SweepKit(**kit))
    positions = {"M1": [3., 2., 1.2], "M2": [3.3, 2., 1.2], "REF_S1": [2.3, 2., 1.]}
    takes = []
    for i, (mic, xyz) in enumerate(positions.items()):
        if mic.startswith("REF"):
            h = np.zeros(4000); h[14] = .3
        else:
            h = _single_reflection(i).samples*.1
        recording = signal.fftconvolve(playback, h)
        wavfile.write(tmp_path/(mic+".wav"), 16000, (recording*32767).astype(np.int16))
        takes.append(dict(file=mic+".wav", type="sweep", speaker="S1", mic=mic))
    if real_and_noise_takes:
        burst = .05*np.random.default_rng(3).standard_normal(1600)
        for mic in ("REF_S1", "M1"):
            wavfile.write(tmp_path/f"{mic}_real.wav", 16000, (burst*32767).astype(np.int16))
            takes.append(dict(file=f"{mic}_real.wav", type="real", speaker="S1", mic=mic, label="burst"))
        wavfile.write(tmp_path/"noise.wav", 16000, np.zeros(1600, np.int16))
        takes.append(dict(file="noise.wav", type="noise", mic="M1"))
    manifest = dict(room_id="test-kit", fs_hz=16000,
                    room=dict(dims_m=dict(x=8, y=8, z=4), surfaces={"floor": "concrete"}),
                    positions=dict(speakers={"S1": [2., 2., 1.]}, mics=positions),
                    takes=takes, excitation=dict(type="ess", kit="sweep_kit.json"))
    path = tmp_path/"manifest.yaml"; path.write_text(yaml.safe_dump(manifest))
    return path


def test_canonical_kit_cli_ignores_real_and_noise_takes_at_ref(tmp_path):
    path = _write_canonical_kit(tmp_path, real_and_noise_takes=True)
    report = run_manifest(path, tmp_path/"out", config=FitConfig(bands=(1000,), bootstrap=0,
        max_nfev=10, rir_duration_s=.25))
    assert len(report["split"]) == 2
    assert {r["split"] for r in report["split"]} == {"train", "test"}
    assert all(r["metadata"]["device_response"] == "REF-corrected" for r in report["observations"])


def test_canonical_kit_cli_keeps_ref_out_of_split_and_writes_portable_model(tmp_path):
    path = _write_canonical_kit(tmp_path)
    report = run_manifest(path, tmp_path/"out", config=FitConfig(bands=(1000,), bootstrap=0, max_nfev=10, rir_duration_s=.25))
    assert len(report["split"]) == 2
    assert {r["split"] for r in report["split"]} == {"train", "test"}
    assert all(r["metadata"]["device_response"] == "REF-corrected" for r in report["observations"])
    restored = RoomModel.from_json((tmp_path/"out/room_model.json").read_text())
    assert len(restored.provenance["training_positions"]) == 1
    # Main's pipeline sends extracted mono RIRs and expects RoomModel directly.
    from sensorsim.acoustics.room.ingest import load_manifest
    from sensorsim.acoustics.room.rir import extract_take
    parsed = load_manifest(path)
    rirs = []
    for i in range(len(parsed.takes)):
        response = extract_take(parsed, i, rir_duration_s=.25)
        rirs.append(RIR(response.fs, response.samples[:, 0], response.source_xyz_m,
                        tuple(np.atleast_2d(response.receiver_xyz_m)[0]), response.metadata))
    integrated = fit_room(manifest=parsed, rirs=rirs,
                          initial_model=RoomModel(shoebox_dims_m=(8, 8, 4), temperature_c=24),
                          config=FitConfig(bands=(1000,), bootstrap=0, max_nfev=10, rir_duration_s=.25))
    assert isinstance(integrated, RoomModel)
    assert integrated.temperature_c == 24
    assert len(integrated.provenance["training_positions"]) == 1
    adapter_report = integrated.provenance["pipeline_fit_report"]
    assert {r["split"] for r in adapter_report["split"]} == {"train", "test"}
    assert all(r["metadata"]["device_response"] == "REF-corrected" for r in adapter_report["observations"])
    with pytest.raises(FileExistsError):
        run_manifest(path, tmp_path/"out")
