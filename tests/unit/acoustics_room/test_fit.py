def test_missing_metrics_are_unavailable_but_invalid_prediction_fails():
    cfg = FitConfig(bands=(1000,), bootstrap=0)
    obs = observe(_single_reflection(0), id="heldout", config=cfg, split="test")
    truth = obs.bands[1000]
    truth.values["t20"] = .2
    missing = replace(truth, values={k: None for k in truth.values})
    predicted = replace(obs, bands={1000: missing})
    model = RoomModel(shoebox_dims_m=(8, 8, 4), provenance={"training_positions": []})
    result = FitResult(model, cfg, {"spectral_gain_db": {"1000": 0.}})
    rows = compare(result, obs, predicted)
    assert next(r for r in rows if r["metric"] == "t20")["status"] == "FAIL"
    truth.values["t30"] = None
    assert next(r for r in compare(result, obs, predicted) if r["metric"] == "t30")["status"] == "UNAVAILABLE"


